"""
Базовый сервис для бизнес-логики приложения.

Предоставляет общий интерфейс для всех сервисов.
"""

from abc import ABC, abstractmethod
from typing import Any


class BaseService(ABC):
    """
    Абстрактный базовый сервис.

    Все сервисы должны наследоваться от этого класса
    и реализовывать метод __call__.
    """

    @abstractmethod
    async def __call__(self, *args: Any, **kwargs: Any) -> Any:
        """
        Основной метод сервиса, вызываемый из контроллеров или зависимостей.

        Args:
            *args: Позиционные аргументы.
            **kwargs: Именованные аргументы.

        Returns:
            Результат выполнения бизнес-логики.
        """
        pass
